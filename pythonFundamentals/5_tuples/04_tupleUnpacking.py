# tuple unpacking - assigning values from tuple to multiple variables
# matched by position

sales = (12000, 15000, 9000)
monday, tuesday, wednesday = sales
print(monday)
print(tuesday)
print(wednesday)



employee = ("Anas", 101, "Data Analyst")
name, emp_id, role = employee
print(name)
print(emp_id)
print(role)